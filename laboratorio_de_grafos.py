def dijkstra_explicado(grafo, origen, destino, peso='peso_km'):
    if origen not in grafo or destino not in grafo:
        raise ValueError('Origen y destino deben existir en el grafo.')
    for _,_,datos in grafo.edges(data=True):
        if peso not in datos or not math.isfinite(datos[peso]) or datos[peso] < 0:
            raise ValueError('Cada conexión debe tener un peso numérico finito y no negativo.')
    distancias = {n:float('inf') for n in grafo.nodes}
    predecesor = {n:None for n in grafo.nodes}
    distancias[origen] = 0.0
    turno = count()
    pendientes = [(0.0,next(turno),origen)]
    confirmados = set()
    seguimiento = []
    relajaciones = []
    while pendientes:
        distancia,_,actual = heapq.heappop(pendientes)
        if actual in confirmados: continue
        confirmados.add(actual)
        for vecino,datos in grafo[actual].items():
            if vecino in confirmados: continue
            propuesta = distancia + datos[peso]
            if propuesta < distancias[vecino]:
                anterior = distancias[vecino]
                distancias[vecino] = propuesta
                predecesor[vecino] = actual
                heapq.heappush(pendientes,(propuesta,next(turno),vecino))
                relajaciones.append({'Desde':actual,'Hacia':vecino,'Anterior km':anterior,
                    'Nueva km':propuesta,'Predecesor':actual})
        seguimiento.append({'Paso':len(seguimiento)+1,'Nodo confirmado':actual,
                            'Distancia confirmada km':distancia,**distancias})
        if actual == destino: break
    if not math.isfinite(distancias[destino]):
        return [],float('inf'),pd.DataFrame(seguimiento),pd.DataFrame(relajaciones)
    camino = []
    actual = destino
    while actual is not None:
        camino.append(actual)
        actual = predecesor[actual]
    camino.reverse()
    return camino,distancias[destino],pd.DataFrame(seguimiento),pd.DataFrame(relajaciones)

