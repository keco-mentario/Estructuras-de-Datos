def kruskal_explicado(grafo, peso='peso_km'):
    if grafo.is_directed():
        raise ValueError('Esta versión de Kruskal requiere un grafo no dirigido.')
    padre = {n:n for n in grafo.nodes}
    def raiz(n):
        while padre[n] != n:
            padre[n] = padre[padre[n]]
            n = padre[n]
        return n
    resultado = nx.Graph()
    resultado.add_nodes_from(grafo.nodes(data=True))
    seguimiento = []
    ordenadas = sorted(grafo.edges(data=True), key=lambda e:e[2][peso])
    for paso,(a,b,d) in enumerate(ordenadas,start=1):
        r1,r2 = raiz(a),raiz(b)
        aceptar = r1 != r2
        if aceptar:
            padre[r2] = r1
            resultado.add_edge(a,b,**d)
        seguimiento.append({'Paso':paso,'Origen':a,'Destino':b,'Peso km':d[peso],
            'Decisión':'Aceptar: une componentes' if aceptar else 'Descartar: formaría ciclo',
            'Aristas aceptadas':resultado.number_of_edges()})
        if resultado.number_of_edges() == grafo.number_of_nodes()-1:
            break
    return resultado,pd.DataFrame(seguimiento)

