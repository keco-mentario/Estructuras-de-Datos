def ruta_osrm(origen, destino):
    global ultima_consulta
    lat1,lon1 = coordenadas[origen]
    lat2,lon2 = coordenadas[destino]
    puntos = f'{lon1},{lat1};{lon2},{lat2}'
    clave = SERVIDOR_OSRM + '|' + puntos
    if clave in cache_rutas:
        r = cache_rutas[clave]
        return r['puntos'],r['km']
    espera = max(0, 1.1-(time.monotonic()-ultima_consulta))
    if espera: time.sleep(espera)
    ultima_consulta = time.monotonic()
    try:
        r = requests.get(f'{SERVIDOR_OSRM}/route/v1/driving/{puntos}',
            params={'overview':'full','geometries':'geojson','radiuses':'500;500'},timeout=35)
        r.raise_for_status()
        datos = r.json()
        if datos.get('code') != 'Ok' or not datos.get('routes'):
            print(f'Sin ruta vial {origen} → {destino}: {datos.get("code")}')
            return None
        ruta = datos['routes'][0]
        puntos_ruta = [(lat,lon) for lon,lat in ruta['geometry']['coordinates']]
        km = ruta['distance']/1000
        cache_rutas[clave] = {'puntos':puntos_ruta,'km':km}
        archivo_cache.write_text(json.dumps(cache_rutas,ensure_ascii=False),encoding='utf-8')
        return puntos_ruta,km
    except (requests.RequestException,ValueError,KeyError) as e:
        print(f'Ruta no disponible {origen} → {destino}: {e}')
        return None

