def matriz_incidencia(grafo, nodos):
    aristas = list(grafo.edges(data=True))
    etiquetas = [f'E{i}' for i in range(1,len(aristas)+1)]
    incidencia = pd.DataFrame(0,index=nodos,columns=etiquetas,dtype=int)
    detalle = []
    for etiqueta,(a,b,d) in zip(etiquetas,aristas):
        incidencia.loc[a,etiqueta] = -1 if grafo.is_directed() else 1
        incidencia.loc[b,etiqueta] = 1
        detalle.append({'Arista':etiqueta,'Origen':a,'Destino':b,'Peso km':d['peso_km']})
    incidencia.index.name = 'Campus / arista'
    return incidencia,pd.DataFrame(detalle,columns=['Arista','Origen','Destino','Peso km'])

